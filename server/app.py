"""Asset register API. Run with: uvicorn server.app:app --host 0.0.0.0 --port 3001."""
import io
import logging
import os
import re
import sqlite3
import warnings
from datetime import datetime, timezone
from pathlib import Path
from typing import Annotated, Literal
from uuid import uuid4

from fastapi import FastAPI, File, Form, HTTPException, Query, Response, UploadFile
from fastapi.staticfiles import StaticFiles
from PIL import Image, ImageOps, UnidentifiedImageError
from pydantic import BaseModel

from .database import connection, initialize, serialize

ROOT = Path(__file__).resolve().parent.parent
MAX_IMAGE_BYTES = 8 * 1024 * 1024
Image.MAX_IMAGE_PIXELS = 25_000_000


class Asset(BaseModel):
    id: int
    assetId: str
    category: str
    photoUrl: str
    createdAt: str
    source: Literal["manual", "automated"]


class Stats(BaseModel):
    totalAssets: int
    totalCategories: int
    addedToday: int


class CategoryCount(BaseModel):
    category: str
    count: int


class AssetPage(BaseModel):
    items: list[Asset]
    total: int
    page: int
    limit: int
    totalPages: int
    stats: Stats
    categories: list[CategoryCount]


def normalize_image(raw: bytes) -> bytes:
    """Decode rather than trust extensions; resize, orient, and strip metadata."""
    try:
        with warnings.catch_warnings():
            warnings.simplefilter("error", Image.DecompressionBombWarning)
            with Image.open(io.BytesIO(raw)) as original:
                if original.format not in {"JPEG", "PNG", "WEBP"} or getattr(original, "n_frames", 1) != 1:
                    raise ValueError("Unsupported image")
                if original.width * original.height > 25_000_000:
                    raise ValueError("Image too large")
                original.load()
                image = ImageOps.exif_transpose(original)
                image.thumbnail((1600, 1600))
                rgba = image.convert("RGBA")
                rgb = Image.new("RGB", rgba.size, "white")
                rgb.paste(rgba, mask=rgba.getchannel("A"))
                output = io.BytesIO()
                rgb.save(output, "JPEG", quality=85, optimize=True)
                return output.getvalue()
    except (UnidentifiedImageError, OSError, ValueError, Image.DecompressionBombError, Image.DecompressionBombWarning) as exc:
        raise HTTPException(400, "Upload a valid, still JPG, PNG, or WebP image (up to 25 megapixels).") from exc


def create_app(data_dir: Path | None = None, dist_dir: Path | None = None):
    storage = Path(data_dir or os.environ.get("DATA_DIR", ROOT / "data")).resolve()
    frontend = Path(dist_dir or ROOT / "dist")
    initialize(storage)
    app = FastAPI(title="Zee Links Asset Register", version="1.0.0", description="Warehouse asset records and photographs. All timestamps are generated by the server in UTC.")

    @app.middleware("http")
    async def security_headers(request, call_next):
        response = await call_next(request)
        response.headers["X-Content-Type-Options"] = "nosniff"
        response.headers["Referrer-Policy"] = "same-origin"
        return response

    @app.get("/api/health", tags=["Health"])
    def health():
        with connection(storage) as db:
            db.execute("SELECT 1").fetchone()
        return {"status": "ok"}

    @app.get("/api/assets", response_model=AssetPage, tags=["Assets"])
    def list_assets(
        q: Annotated[str, Query(max_length=80)] = "",
        category: Annotated[str, Query(max_length=60)] = "",
        page: Annotated[int, Query(ge=1, le=100000)] = 1,
        limit: Annotated[int, Query(ge=1, le=100)] = 12,
        sort: Literal["newest", "oldest"] = "newest",
    ):
        clauses, values = [], []
        if q.strip():
            clauses.append("asset_id LIKE ? ESCAPE '\\'")
            escaped = re.sub(r"([\\%_])", r"\\\1", q.strip())
            values.append(f"%{escaped}%")
        if category.strip():
            clauses.append("category = ?")
            values.append(category.strip())
        where = "WHERE " + " AND ".join(clauses) if clauses else ""
        order = "ASC" if sort == "oldest" else "DESC"
        today = datetime.now(timezone.utc).date().isoformat()
        with connection(storage) as db:
            total = db.execute(f"SELECT COUNT(*) FROM assets {where}", values).fetchone()[0]
            items = db.execute(f"SELECT * FROM assets {where} ORDER BY created_at {order}, id {order} LIMIT ? OFFSET ?", [*values, limit, (page - 1) * limit]).fetchall()
            stats = db.execute("""SELECT COUNT(*) AS totalAssets, COUNT(DISTINCT category) AS totalCategories,
                COALESCE(SUM(substr(created_at, 1, 10) = ?), 0) AS addedToday FROM assets""", [today]).fetchone()
            categories = db.execute("SELECT category, COUNT(*) AS count FROM assets GROUP BY category ORDER BY category").fetchall()
        return {"items": [serialize(row) for row in items], "total": total, "page": page, "limit": limit,
                "totalPages": (total + limit - 1) // limit, "stats": dict(stats), "categories": [dict(row) for row in categories]}

    @app.get("/api/assets/{record_id}", response_model=Asset, tags=["Assets"])
    def get_asset(record_id: int):
        with connection(storage) as db:
            row = db.execute("SELECT * FROM assets WHERE id = ?", [record_id]).fetchone()
        if row is None:
            raise HTTPException(404, "Asset not found.")
        return serialize(row)

    @app.post("/api/assets", status_code=201, response_model=Asset, tags=["Assets"], responses={400: {"description": "Invalid fields or photograph"}, 409: {"description": "Asset ID already exists"}})
    def create_asset(
        response: Response,
        assetId: Annotated[str, Form(max_length=80)],
        category: Annotated[str, Form(max_length=60)],
        photo: Annotated[UploadFile, File(description="Still JPEG, PNG, or WebP; maximum 8 MB / 25 megapixels")],
        source: Annotated[Literal["manual", "automated"], Form()] = "manual",
    ):
        asset_id, asset_category = assetId.strip(), category.strip()
        if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9 ._/-]{0,79}", asset_id):
            raise HTTPException(400, "Asset ID must start with a letter or number. Use letters, numbers, spaces, dots, dashes, slashes, or underscores.")
        if not asset_category or re.search(r"[\x00-\x1f\x7f]", asset_category):
            raise HTTPException(400, "Enter an asset category between 1 and 60 characters.")
        with connection(storage) as db:
            if db.execute("SELECT id FROM assets WHERE asset_id = ?", [asset_id]).fetchone():
                raise HTTPException(409, "An asset with this ID already exists.")
        raw = photo.file.read(MAX_IMAGE_BYTES + 1)
        if len(raw) > MAX_IMAGE_BYTES:
            raise HTTPException(400, "Photograph must be 8 MB or smaller.")
        encoded = normalize_image(raw)
        filename = f"{uuid4()}.jpg"
        photo_path = storage / "uploads" / filename
        try:
            photo_path.write_bytes(encoded)
            created_at = datetime.now(timezone.utc).isoformat(timespec="milliseconds").replace("+00:00", "Z")
            with connection(storage) as db:
                cursor = db.execute("INSERT INTO assets (asset_id, category, photo_filename, created_at, source) VALUES (?, ?, ?, ?, ?)",
                                    [asset_id, asset_category, filename, created_at, source])
                row = db.execute("SELECT * FROM assets WHERE id = ?", [cursor.lastrowid]).fetchone()
        except sqlite3.IntegrityError as exc:
            photo_path.unlink(missing_ok=True)
            raise HTTPException(409, "An asset with this ID already exists.") from exc
        except Exception as exc:
            photo_path.unlink(missing_ok=True)
            logging.exception("Could not save asset")
            raise HTTPException(500, "Could not save the asset. Please try again.") from exc
        response.headers["Location"] = f'/api/assets/{row["id"]}'
        return serialize(row)

    app.mount("/uploads", StaticFiles(directory=storage / "uploads"), name="uploads")
    # Reserve unknown API paths before mounting the frontend at root.
    @app.api_route("/api/{unmatched:path}", methods=["GET", "POST", "PUT", "DELETE", "PATCH"], include_in_schema=False)
    def unknown_api(unmatched: str):
        raise HTTPException(404, "API endpoint not found.")

    if (frontend / "index.html").exists():
        app.mount("/", StaticFiles(directory=frontend, html=True), name="frontend")
    return app


app = create_app()
